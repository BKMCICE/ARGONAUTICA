"""Plan/check fixed INT8 layer storage; inputs stay live through their consumer."""
import argparse
import hashlib
import json
import re
from pathlib import Path


def require(condition, message):
    if not condition:
        raise ValueError(message)


def read_graph(path):
    text = path.read_text(encoding='utf-8-sig').replace('\r\n', '\n')
    count = int(re.search(r'#define YOLO_LAYER_COUNT (\d+)', text)[1])
    layers = []
    for line in text.splitlines():
        match = re.search(r'/\* layer (\d+) \*/', line)
        if not match:
            continue
        values = list(map(int, re.findall(r'-?\d+', line.split('/*')[0])))
        require(len(values) == 25 and int(match[1]) == len(layers), 'Invalid graph row')
        require(values[0] in range(1, 8) and 0 <= values[21] <= 4, 'Invalid graph kind/sources')
        size = values[4] * values[5] * values[6]
        require(size > 0, 'Empty layer output')
        layers.append(dict(index=len(layers), kind=values[0], bytes=size,
                           sources=values[12:12+values[21]]))
    require(len(layers) == count, 'Incomplete graph')
    return layers, hashlib.sha256(text.encode('utf-8')).hexdigest().upper()


def lifetimes(layers):
    last = list(range(len(layers)))
    heads = []
    for index, layer in enumerate(layers):
        kind = layer['kind']
        require(kind in range(1, 8) and layer['bytes'] > 0, 'Invalid layer')
        if kind == 2:
            require(bool(layer['sources']), 'Route without sources')
            reads = layer['sources']
        else:
            reads = [index-1] if index else []
            if kind == 3:
                require(len(layer['sources']) == 1, 'Shortcut needs one source')
                reads = reads + layer['sources']
        for source in reads:
            require(0 <= source < index, 'Non-causal graph edge')
            last[source] = max(last[source], index)
        if kind == 7:
            heads.append(index)
    # Final hashes and box decode read both outputs after the entire forward loop.
    for index in heads:
        last[index] = len(layers)
    return last, heads


def align_up(value, alignment):
    return (value + alignment-1) // alignment * alignment


def validate(layers, offsets, arena_bytes, alignment=32):
    require(alignment > 0 and alignment & (alignment-1) == 0, 'Alignment must be power of two')
    require(len(offsets) == len(layers) and arena_bytes > 0, 'Invalid allocation size')
    last, _ = lifetimes(layers)
    for i, (layer, offset) in enumerate(zip(layers, offsets)):
        size = align_up(layer['bytes'], alignment)
        require(isinstance(offset, int) and offset >= 0 and offset % alignment == 0, 'Unaligned/negative offset')
        require(offset + size <= arena_bytes, 'Output exceeds arena')
        for j in range(i):
            if last[j] >= i:
                other_size = align_up(layers[j]['bytes'], alignment)
                require(offset + size <= offsets[j] or offsets[j] + other_size <= offset,
                        f'Live layer overlap: {j} and {i}')


def plan(layers, alignment=32):
    require(alignment > 0 and alignment & (alignment-1) == 0, 'Alignment must be power of two')
    last, heads = lifetimes(layers)
    active, offsets, arena_bytes, peak_live = [], [], 0, 0
    for i, layer in enumerate(layers):
        active = [item for item in active if item[2] >= i]
        size, offset = align_up(layer['bytes'], alignment), 0
        for start, length, end in sorted(active):
            if offset + size <= start:
                break
            offset = max(offset, start + length)
        offsets.append(offset)
        active.append((offset, size, last[i]))
        arena_bytes = max(arena_bytes, offset+size)
        peak_live = max(peak_live, sum(item[1] for item in active))
    validate(layers, offsets, arena_bytes, alignment)
    return dict(result='ARENA_PLAN_PASS', alignment=alignment, arena_bytes=arena_bytes,
                original_bytes=sum(layer['bytes'] for layer in layers),
                peak_live_padded_bytes=peak_live, retained_heads=heads,
                offsets=offsets, last_use=last, layers=layers,
                scope='First-fit static allocation, no in-place operators or alias elimination. '
                      'Producer and final consumer lifetimes overlap inclusively. Heads pinned '
                      'through final decode. Not an optimality, speed or physical-board claim.')


def render_header(result, graph_sha):
    rows = ['/* Generated by tools/yolo_plan_arena.py; do not edit. */',
            '#ifndef YOLO_MODEL_ARENA_H', '#define YOLO_MODEL_ARENA_H', '#include <stdint.h>',
            f'#define YOLO_COMPACT_ACTIVATION_BYTES {result["arena_bytes"]}u',
            f'#define YOLO_ARENA_GRAPH_SHA256 "{graph_sha}"',
            'static const uint32_t yolo_compact_offsets[YOLO_LAYER_COUNT] = {']
    values = result['offsets']
    rows.extend('  '+', '.join(str(v)+'u' for v in values[i:i+8])+',' for i in range(0,len(values),8))
    return '\n'.join(rows + ['};', '#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--graph', type=Path, required=True)
    parser.add_argument('--header', type=Path, required=True)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    layers, digest = read_graph(args.graph)
    result = plan(layers)
    expected = render_header(result, digest)
    if args.check:
        require(args.header.read_text(encoding='utf-8-sig').replace('\r\n','\n') == expected,
                'Stale/modified arena header; regenerate with yolo_plan_arena.py')
    else:
        args.header.write_text(expected, encoding='ascii')
    result['normalized_model_graph_sha256'] = digest
    result['header_sha256_normalized'] = hashlib.sha256(expected.encode('ascii')).hexdigest().upper()
    if args.output:
        args.output.write_text(json.dumps(result, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({key:result[key] for key in ['result','original_bytes','arena_bytes',
                                               'peak_live_padded_bytes','retained_heads']}))


if __name__ == '__main__':
    main()

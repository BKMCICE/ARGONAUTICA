"""Emit a CHW INT8 sample image and static RV32 graph table for YOLO-Fastest."""
import hashlib
import json
import math
from pathlib import Path

import numpy as np
import torch

from yolo_int8_reference import forward_fixed, layer_params, load_image
from yolo_model_manifest import manifest, parse_cfg


KINDS = {"convolutional": 1, "route": 2, "shortcut": 3, "maxpool": 4,
         "upsample": 5, "dropout": 6, "yolo": 7}


def fnv(data: bytes) -> int:
    value = 2166136261
    for byte in data:
        value = ((value ^ byte) * 16777619) & 0xFFFFFFFF
    return value


def emit(model_dir: Path, out_dir: Path) -> None:
    cfg = model_dir / "yolo-fastest-1.1.cfg"
    layout = manifest(cfg, model_dir / "yolo-fastest-1.1.weights")
    sections = parse_cfg(cfg)[1:]
    fixed = json.loads((model_dir / "fixed_manifest.json").read_text(encoding="utf-8"))
    scales = json.loads((model_dir / "activation_scales_2img.json").read_text(encoding="utf-8"))["scales"]
    params = layer_params(model_dir, layout)
    height, width, channels = layout["input_shape"]
    torch.set_num_threads(1)
    x = load_image(model_dir / "dog.jpg", width, height)
    pixels = torch.clamp(torch.round(x * 127), -127, 127).to(torch.int8).contiguous().numpy()
    image_bytes = pixels.tobytes()
    out_dir.mkdir(parents=True, exist_ok=True)
    (model_dir / "dog_chw_int8.bin").write_bytes(image_bytes)
    with torch.no_grad():
        outputs = forward_fixed(x, sections, layout, params, scales, fixed,
                                (model_dir / "params_q24.bin").read_bytes())
    heads = [(layer["index"], fnv(outputs[layer["index"]].contiguous().numpy().tobytes()))
             for layer in layout["layers"] if layer["type"] == "yolo"]

    lines = ["/* Generated by tools/yolo_emit_rv32.py; do not edit by hand. */",
             "#ifndef YOLO_MODEL_GRAPH_H", "#define YOLO_MODEL_GRAPH_H", "#include <stdint.h>",
             "#define YOLO_LAYER_COUNT 131", "#define YOLO_INPUT_BYTES 307200",
             "#define YOLO_LEAKY_Q24 1677722", "enum { YOLO_CONV=1, YOLO_ROUTE=2, YOLO_SHORTCUT=3,",
             "       YOLO_MAXPOOL=4, YOLO_UPSAMPLE=5, YOLO_DROPOUT=6, YOLO_HEAD=7 };",
             "typedef struct {", "  uint32_t kind, ih, iw, ic, oh, ow, oc;",
             "  uint32_t size, stride, groups, pad, leaky;",
             "  int32_t sources[4], source_q24[4], prev_q24;",
             "  uint32_t source_count, weight_offset, param_offset, output_offset;",
             "} YoloLayer;", "static const YoloLayer yolo_layers[YOLO_LAYER_COUNT] = {"]
    offset = 0
    for op in fixed["layers"]:
        idx = op["index"]
        in_shape = op["input"] if op["input"] is not None else (
            layout["input_shape"] if idx == 0 else fixed["layers"][idx - 1]["shape"])
        out_shape = op["shape"]
        sources = op.get("sources", [op["source"]] if "source" in op else [])
        source_q24 = op.get("source_q24", [])
        if isinstance(source_q24, int):
            source_q24 = [source_q24]
        if len(sources) > 4:
            raise ValueError("too many route sources")
        src = sources + [-1] * (4 - len(sources))
        mul = source_q24 + [0] * (4 - len(source_q24))
        base = [KINDS[op["type"]], *in_shape, *out_shape,
                op.get("kernel_size", op.get("size", 0)), op.get("stride", 1),
                op.get("groups", 1), op.get("padding", op.get("size", 0) // 2 if op["type"] == "maxpool" else 0),
                int(op.get("activation") == "leaky")]
        tail = [op.get("previous_q24", 0), len(sources), op.get("weight_offset", 0),
                op.get("param_offset", 0), offset]
        lines.append("  {" + ", ".join(str(v) for v in base) +
                     ", {" + ", ".join(str(v) for v in src) + "}, {" +
                     ", ".join(str(v) for v in mul) + "}, " +
                     ", ".join(str(v) for v in tail) + "}, /* layer " + str(idx) + " */")
        offset += out_shape[0] * out_shape[1] * out_shape[2]
    lines += ["};", f"#define YOLO_ACTIVATION_BYTES {offset}",
              f"#define YOLO_DOG_IMAGE_FNV 0x{fnv(image_bytes):08x}u",
              f"#define YOLO_HEAD0_FNV 0x{heads[0][1]:08x}u",
              f"#define YOLO_HEAD1_FNV 0x{heads[1][1]:08x}u",
              "extern const int8_t yolo_weights[], yolo_dog_image[];",
              "extern const int32_t yolo_params_q24[];", "#endif"]
    (out_dir / "model_graph.h").write_text("\n".join(lines) + "\n", encoding="ascii")
    head_sections = [sec for sec, layer in zip(sections, layout["layers"])
                     if layer["type"] == "yolo"]
    lookup = ["/* Generated host reference lookup tables for RV32 box decode. */",
              "#ifndef YOLO_POSTPROCESS_LUT_H", "#define YOLO_POSTPROCESS_LUT_H", "#include <stdint.h>"]
    for head_number, (index, _) in enumerate(heads):
        scale = scales[index]
        sigmoid = []
        exponential = []
        for byte in range(256):
            signed = byte if byte < 128 else byte - 256
            value = signed * scale
            sigmoid.append(round((1 / (1 + math.exp(-value))) * 32767))
            exponential.append(round(math.exp(max(-10, min(10, value))) * 65536))
        lookup.append(f"static const uint16_t yolo_sigmoid_{head_number}[256] = {{")
        lookup.extend("  " + ", ".join(str(v) for v in sigmoid[i:i + 16]) + ","
                      for i in range(0, 256, 16))
        lookup.append("};")
        lookup.append(f"static const uint32_t yolo_exp_{head_number}[256] = {{")
        lookup.extend("  " + ", ".join(str(v) for v in exponential[i:i + 8]) + ","
                      for i in range(0, 256, 8))
        lookup.append("};")
    anchors_flat = [int(v) for v in head_sections[0]["anchors"].split(",")]
    anchors = list(zip(anchors_flat[::2], anchors_flat[1::2]))
    masks = [[int(v) for v in sec["mask"].split(",")] for sec in head_sections]
    lookup.append("static const uint16_t yolo_anchors[2][3][2] = {")
    for mask in masks:
        lookup.append("  {" + ", ".join("{" + f"{anchors[i][0]}, {anchors[i][1]}" + "}"
                                       for i in mask) + "},")
    lookup.append("};")
    names = (model_dir / "coco.names").read_text(encoding="utf-8").splitlines()
    lookup.append("static const char * const yolo_names[80] = {")
    lookup.extend("  " + json.dumps(name) + "," for name in names)
    lookup.extend(["};", "#endif"])
    (out_dir / "postprocess_lut.h").write_text("\n".join(lookup) + "\n", encoding="ascii")
    print(f"input_bytes={len(image_bytes)} input_sha256={hashlib.sha256(image_bytes).hexdigest()}")
    print(f"activation_bytes={offset} heads={[(i, f'{v:08x}') for i, v in heads]}")


if __name__ == "__main__":
    root = Path(__file__).resolve().parent.parent
    emit(root / "models/yolo_fastest_1_1", root / "sw/yolo_fixed")

"""Write a PDS Fabric Inserter project for the cached DDR SoC.

The FIC must point at that build's exact ADS ADF (PDS can register it before
synthesis). Default pipeline probes were checked on S11; the DDR profile uses
the S22 synthesized net names and must be rechecked after structural RTL changes.
"""

import argparse
from pathlib import Path


PROBES = (
    "u_soc/u_core/mem_commit",
    "u_soc/u_core/mem_adv",
    "u_soc/u_core/exmem_valid",
    "u_soc/u_core/exmem_mispred",
    "u_soc/ev_ds",
    "u_soc/u_dcache/miss_event",
    "u_soc/line_req",
    "u_soc/line_ready",
)

# Keep this at eight bits / 512 samples like the pipeline profile. Probe the
# controller handshake nets. ADS folds RVALID/RLAST into internal logic; the
# read-wait state and the controller data-valid net survive in the S22 ADF.
DDR_PROBES = (
    "arvalid", "arready",
    "u_ddr/u_ipsxb_ddrc_top/mcdq_rdatapath/data_out_valid",
    "u_soc/u_ddr_bridge/state_reg[4]",
    "awvalid", "awready", "wready", "u_soc/line_ready",
)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--adf", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--replace", action="store_true")
    parser.add_argument("--profile", choices=("pipeline", "ddr"), default="pipeline")
    args = parser.parse_args()
    probes = DDR_PROBES if args.profile == "ddr" else PROBES
    # PDS registers the FIC before synthesis, so its ADF is created later.
    adf = args.adf.resolve()
    output = args.output.resolve()
    if output.exists() and not args.replace:
        raise FileExistsError(output)
    lines = [
        "#Fabric Core Inserter Project File",
        "#Generated by tools/create_ila_fic.py for PDS 2022.2-SP6.4",
        "Project.type=inserter",
        f"Project.device.designInputFile={adf.as_posix()}",
        "Project.device.ScanChain=1",
        "Project.device.UserJtag=0",
        "Project.Architecture=1 1 1 ",
        "Project.unit.dimension=1",
        "Project.unit<0>.clockChannel=ui_clk",
        "Project.unit<0>.clockEdge=Rising",
        "Project.unit<0>.ramType=1",
        "Project.unit<0>.dataDepth=512",
        "Project.unit<0>.dataEqualsTrigger=true",
        "Project.unit<0>.enablePowerOnInitData=false",
        "Project.unit<0>.enableStorageQualification=false",
        "Project.unit<0>.triggerSequencerLevels=1",
        "Project.unit<0>.enableMultiWindow=false",
        "Project.unit<0>.triggerPortCount=1",
    ]
    lines.extend(
        f"Project.unit<0>.triggerChannel<0><{index}>={name}"
        for index, name in enumerate(probes)
    )
    lines.extend(
        (
            "Project.unit<0>.triggerMatchCount<0>=1",
            "Project.unit<0>.triggerMatchCountWidth<0>=0",
            "Project.unit<0>.triggerMatchType<0>=1",
            "Project.unit<0>.triggerPortIsData<0>=true",
            f"Project.unit<0>.triggerPortWidth<0>={len(probes)}",
        )
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"FIC={output} profile={args.profile} probes={len(probes)} adf={adf}")


if __name__ == "__main__":
    main()
